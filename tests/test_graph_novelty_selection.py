"""Paired, bounded Φ⁴ novelty-selection probe (research; not a generator change).

This invokes the *actual* Psi function on one synthetic graph-history
reference. It compares identical starting PRNG streams under d_min=0.0
(one candidate) versus d_min=0.99 (14 candidates at phase 4). The latter
target exceeds the normalized distance ceiling and intentionally exhausts
the existing retry budget. These are controlled, artificial phase-4
conditions, not natural phase progression or measured deployment rates.

Run: python -m unittest -v tests.test_graph_novelty_selection
"""
import json
import random
import sys
import unittest
from collections import Counter
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import origin_engine_monolith as oe


def is_connected(graph):
    """Independent BFS, rather than using the scorecard under investigation."""
    nodes = graph["nodes"]
    assert len(nodes) == 5 and [n["id"] for n in nodes] == list(range(5))
    adjacency = {i: set() for i in range(5)}
    seen_edges = set()
    for edge in graph["edges"]:
        a, b = edge["source"], edge["target"]
        assert type(a) is int and type(b) is int and 0 <= a < b < 5
        assert (a, b) not in seen_edges
        seen_edges.add((a, b))
        adjacency[a].add(b)
        adjacency[b].add(a)
    visited, todo = {0}, [0]
    while todo:
        at = todo.pop()
        for nxt in adjacency[at] - visited:
            visited.add(nxt)
            todo.append(nxt)
    return len(visited) == 5


def run_probe():
    iota = oe.Iota(ident="0123456789abcdef", orbit=7, entropy_mark="1234abcd")
    # A reproducible, nonempty synthetic history, itself generated by Ψ.
    # It is intentionally not an observed natural engine trajectory.
    with patch.object(oe, "_dump_graph_file", return_value="<not-written>") as initial_dump:
        reference = oe.Ψ(iota, [], oe.Phase(level=4),
                         d_min=0.0, rng=random.Random(8642)).payload
        assert initial_dump.call_count == 1
    stats = {"first": Counter(), "best_of_14": Counter()}
    examples = []
    with patch.object(oe, "_dump_graph_file", return_value="<not-written>") as dump:
        for seed in range(64):
            runs = []
            for threshold, name, expected_retries in (
                (0.0, "first", 1), (0.99, "best_of_14", 14)
            ):
                candidate = oe.Ψ(iota, [reference], oe.Phase(level=4),
                                 d_min=threshold, rng=random.Random(seed))
                graph = candidate.meta["graph"]
                assert candidate.meta["retries"] == expected_retries
                connected = is_connected(graph)
                stats[name]["connected" if connected else "disconnected"] += 1
                stats[name]["edges"] += len(graph["edges"])
                runs.append(candidate)
            assert runs[1].meta["novelty_score"] >= runs[0].meta["novelty_score"]
            if runs[1].meta["graph"] != runs[0].meta["graph"]:
                examples.append(seed)
        assert dump.call_count == 128  # 64 paired output choices
    return {"synthetic_reference_chars": len(reference), "seeds": 64,
            "observations_per_condition": 64,
            "first": dict(stats["first"]), "best_of_14": dict(stats["best_of_14"]),
            "changed_selected_graph_seeds": len(examples),
            "changed_seed_examples": examples[:12],
            "scope": "fixed synthetic one-entry history, forced phase 4, in-memory exports"}


class PhaseFourNoveltyProbe(unittest.TestCase):
    def test_reproducible_paired_selection_without_graph_writes(self):
        first = run_probe()
        second = run_probe()
        self.assertEqual(first, second)
        self.assertEqual(first["seeds"], 64)
        for condition in ("first", "best_of_14"):
            self.assertEqual(first[condition].get("connected", 0)
                             + first[condition].get("disconnected", 0), 64)
        print("GRAPH_NOVELTY_PROBE " + json.dumps(first, sort_keys=True))


if __name__ == "__main__":
    unittest.main()
